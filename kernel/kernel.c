static void hline(int x,int y,int w,u8 c){for(int i=0;i<w;i++)pixel(x+i,y,c);}
static void vline(int x,int y,int h,u8 c){for(int i=0;i<h;i++)pixel(x,y+i,c);}
static void draw_char(int x,int y,char ch,u8 c){/* tiny 5x7 font hook; glyph data is expanded below */(void)x;(void)y;(void)ch;(void)c;}
static void draw_text(int x,int y,const char*s,u8 c){while(*s){draw_char(x,y,*s++,c);x+=6;}}
static void push_event(u32 t,u32 a,u32 b,u32 c){u32 n=(event_head+1)%MAX_EVENTS;if(n==event_tail)return;events[event_head]=(Event){t,a,b,c};event_head=n;}
static int pop_event(Event*e){if(event_tail==event_head)return 0;*e=events[event_tail];event_tail=(event_tail+1)%MAX_EVENTS;return 1;}
static void *kmalloc(usize n){n=(n+15)&~15;if(heap_cursor+n<0x00800000){void*p=(void*)heap_cursor;heap_cursor+=n;memset8(p,0,n);return p;}return 0;}
static int rect_hit(int x,int y,int w,int h,int px,int py){return px>=x&&py>=y&&px<x+w&&py<y+h;}
