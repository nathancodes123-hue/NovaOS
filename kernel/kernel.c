static void memcpy8(void *d,const void *s,usize n){u8 *a=d;const u8*b=s;while(n--)*a++=*b++;}
static usize strlen8(const char*s){usize n=0;while(s&&s[n])n++;return n;}
static void text_clear(void){for(u32 y=0;y<25;y++)for(u32 x=0;x<80;x++)text[y*80+x]=(u16)(0x0700|' ');cursor_x=cursor_y=0;}
static void text_put(char c){if(c=='\n'){cursor_x=0;if(++cursor_y>=25)cursor_y=0;return;}text[cursor_y*80+cursor_x]=(u16)(0x0700|(u8)c);if(++cursor_x>=80){cursor_x=0;if(++cursor_y>=25)cursor_y=0;}}
static void text_print(const char*s){while(*s)text_put(*s++);}
static void text_hex(u32 v){const char*h="0123456789ABCDEF";text_print("0x");for(int i=7;i>=0;i--)text_put(h[(v>>(i*4))&15]);}
static void pixel(int x,int y,u8 c){if(x>=0&&x<SCREEN_W&&y>=0&&y<SCREEN_H)fb[y*SCREEN_W+x]=c;}
static void rect(int x,int y,int w,int h,u8 c){for(int yy=0;yy<h;yy++)for(int xx=0;xx<w;xx++)pixel(x+xx,y+yy,c);}
